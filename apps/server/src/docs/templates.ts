export function buildDoc(kind: DocKind, d: DocData): Promise<Buffer> {
  const ranepa = d.vuz.form === 'ranepa';
  switch (kind) {
    case 'contract':
    case 'consent_letter':
      if (!d.company) throw new Error('Реквизиты компании не заполнены');
      if (kind === 'consent_letter') return consentLetter(d, d.company);
      return ranepa ? contractRanepa(d, d.company) : contract(d, d.company);
    case 'task':
      return ranepa ? taskRanepa(d) : task(d);
    case 'review':
      return ranepa ? reviewRanepa(d) : review(d);
  }
}
