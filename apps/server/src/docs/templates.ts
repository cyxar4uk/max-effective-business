/**
 * Управляющие символы, запрещённые в XML 1.0, → пробел: с ними Word считает файл повреждённым. Попадают при вставке
 * из Word (Shift+Enter даёт \v) в реквизиты, имя в MAX или анкету.
 */
// eslint-disable-next-line no-control-regex -- вырезаем именно управляющие символы
export const xmlSafe = (s: string) => s.replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F￾￿]/g, ' ');

const FONT = 'Times New Roman';
const SIZE = 24; // половины пункта: 12 pt

function para(text: string, opts: { bold?: boolean; center?: boolean; right?: boolean; left?: boolean; after?: number } = {}): Paragraph {
  return new Paragraph({
    alignment: opts.center ? AlignmentType.CENTER : opts.right ? AlignmentType.RIGHT : opts.left ? AlignmentType.LEFT : AlignmentType.JUSTIFIED,
    spacing: { after: opts.after ?? 120 },
    children: [new TextRun({ text: xmlSafe(text), bold: opts.bold, font: FONT, size: SIZE })],
  });
}

const heading = (text: string) => para(text, { bold: true, center: true, after: 200 });

function table(rows: string[][], header = false): Table {
  const cols = Math.max(...rows.map((r) => r.length));
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    rows: rows.map(
      (r, i) =>
        new TableRow({
          children: Array.from({ length: cols }, (_, c) =>
            new TableCell({
              width: { size: Math.floor(100 / cols), type: WidthType.PERCENTAGE },
              // В узкой ячейке выравнивание по ширине растягивает пробелы — только по левому краю
              children: (r[c] ?? '').split('\n').map((line) => para(line, { bold: header && i === 0, left: true, after: 60 })),
            }),
          ),
        }),
    ),
  });
}

function pack(children: (Paragraph | Table)[]): Promise<Buffer> {
  const doc = new Document({
    creator: 'Тандем',
    title: 'Документы для практики',
    styles: { default: { document: { run: { font: FONT, size: SIZE } } } },
    sections: [{ properties: { page: { margin: { top: 1134, bottom: 1134, left: 1701, right: 850 } } }, children }],
  });
  return Packer.toBuffer(doc);
}

const or = (v: string | null | undefined, fallback = BLANK) => (v && v.trim() ? v : fallback);
const responsibleLine = (c: CompanyData) =>
  [`${c.responsiblePosition} ${c.responsibleName}`, c.responsiblePhone, c.responsibleEmail].filter(Boolean).join(', ');

