/** Вуз из анкеты студента → реквизиты: РАНХиГС из шаблона, у остальных только название. */
export function vuzFor(university: string | null): VuzData {
  if (university && /ранхигс|ранепа|ranepa|президентск/i.test(university)) return RANEPA;
  return { legalName: university?.trim() || BY_VUZ, inn: null, ogrn: null, address: null };
}

/** «2026-11-02» → «02.11.2026»; нет даты — пустое поле. */
export function ruDate(iso: string | null): string {
  const m = iso ? /^(\d{4})-(\d{2})-(\d{2})/.exec(iso) : null;
  return m ? `${m[3]}.${m[2]}.${m[1]}` : BLANK;
}

